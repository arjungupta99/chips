// ------------------------------------------------------------------- write out

/** Files we generated last time that no longer have a source, so a renamed event cleans up. */
function staleFiles(directory: string, suffix: string): string[] {
  if (!existsSync(directory)) return [];
  return readdirSync(directory)
    .filter((name) => name.endsWith(suffix))
    .map((name) => join(directory, name))
    .filter((path) => !written.has(path));
}

const stale = [
  ...staleFiles(SCHEMA_DIR, ".json"),
  ...staleFiles(PUBLIC_SCHEMA_DIR, ".json"),
  ...staleFiles(REFERENCE_DIR, ".md"),
];

if (check) {
  const problems: string[] = [];
  for (const [path, content] of written) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
    if (current !== content)
      problems.push(`${current === undefined ? "missing" : "stale"}: ${relative(REPO, path)}`);
  }
  for (const path of stale) problems.push(`orphaned: ${relative(REPO, path)}`);

  if (problems.length > 0) {
    console.error("Generated protocol files are out of date. Run: pnpm gen:protocol\n");
    for (const problem of problems) console.error(`  ${problem}`);
    process.exit(1);
  }
  console.log(`Generated protocol files are up to date (${written.size} files).`);
} else {
  for (const [path, content] of written) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  for (const path of stale) rmSync(path);
  console.log(
    `Wrote ${written.size} files${stale.length > 0 ? `, removed ${stale.length} stale` : ""}.`,
  );
}
