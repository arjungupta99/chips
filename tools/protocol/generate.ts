/**
 * `pnpm gen:protocol` — the one command that turns the Zod schemas into everything else
 * (technical-plan decision 7, milestone M0.2).
 *
 *   packages/protocol/generated/schema/<type>.json   JSON Schema, one per event
 *   packages/protocol/generated/agent-connect.json   the bundle, with a oneOf over all events
 *   packages/protocol/generated/types.ts             TypeScript types, with no zod dependency
 *   apps/docs/.../reference/events/<type>.md         one reference page per event
 *
 * With `--check` it writes nothing and exits non-zero if anything on disk differs, which is
 * how CI fails on stale generated files.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { EVENT_SCHEMAS, EVENTS, PROTOCOL_VERSION } from "@chipschat/protocol";
import { z } from "zod";

const REPO = fileURLToPath(new URL("../../", import.meta.url));
const SCHEMA_DIR = join(REPO, "packages/protocol/generated/schema");
const BUNDLE = join(REPO, "packages/protocol/generated/agent-connect.json");
const TYPES = join(REPO, "packages/protocol/generated/types.ts");
const REFERENCE_DIR = join(REPO, "apps/docs/src/content/docs/reference/events");
/** The docs site serves the JSON Schema, so `/schema/run.started.json` is a real URL. */
const PUBLIC_SCHEMA_DIR = join(REPO, "apps/docs/public/schema");
const FIXTURE_DIR = join(REPO, "packages/protocol/fixtures");

const BANNER = "Generated by `pnpm gen:protocol`. Do not edit by hand.";
const check = process.argv.includes("--check");
const written = new Map<string, string>();

/** Collect a file's intended content. Nothing touches the disk until the end. */
function emit(path: string, content: string): void {
  written.set(path, content.endsWith("\n") ? content : `${content}\n`);
}

// ---------------------------------------------------------------- JSON Schema

/**
 * The URL segment for an event type. Astro strips a dot out of a slug, so `approval.request`
 * would become `/approvalrequest/`; a hyphen keeps the page readable and linkable. The title
 * stays the dotted type, because that is what a reader is looking for.
 */
function slug(type: string): string {
  return type.replace(/\./g, "-");
}

/**
 * A YAML scalar that survives a colon, a quote or a leading dash. Front matter is parsed
 * before anything else, so an unquoted description with a colon in it fails the whole build.
 */
function yaml(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** `run.started` -> `RunStarted`. */
function pascal(type: string): string {
  return type
    .split(/[.\-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const jsonSchemas = new Map<string, Record<string, unknown>>();
for (const event of EVENTS) {
  const schema = EVENT_SCHEMAS.get(event.type);
  if (schema === undefined) throw new Error(`no schema for ${event.type}`);
  const json = z.toJSONSchema(schema, { io: "input", target: "draft-2020-12" }) as Record<
    string,
    unknown
  >;
  json["$id"] = `https://chipschat.ai/schema/v${PROTOCOL_VERSION}/${event.type}.json`;
  json["title"] = pascal(event.type);
  jsonSchemas.set(event.type, json);
  const serialized = JSON.stringify(json, null, 2);
  emit(join(SCHEMA_DIR, `${event.type}.json`), serialized);
  emit(join(PUBLIC_SCHEMA_DIR, `${event.type}.json`), serialized);
}

const bundle = JSON.stringify(
  {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: `https://chipschat.ai/schema/v${PROTOCOL_VERSION}/agent-connect.json`,
    title: "Agent Connect",
    description: `Every event in Agent Connect v${PROTOCOL_VERSION}. ${BANNER}`,
    oneOf: EVENTS.map((event) => ({ $ref: `#/$defs/${pascal(event.type)}` })),
    $defs: Object.fromEntries(EVENTS.map((e) => [pascal(e.type), jsonSchemas.get(e.type)])),
  },
  null,
  2,
);
emit(BUNDLE, bundle);
emit(join(PUBLIC_SCHEMA_DIR, "agent-connect.json"), bundle);

// ------------------------------------------------------------ TypeScript types

/** Render a JSON Schema node as a TypeScript type. Covers the subset our schemas use. */
function toType(node: Record<string, unknown>, indent: string): string {
  if (Array.isArray(node["oneOf"]) || Array.isArray(node["anyOf"])) {
    const branches = (node["oneOf"] ?? node["anyOf"]) as Record<string, unknown>[];
    return branches.map((branch) => toType(branch, indent)).join(" | ");
  }
  if (node["const"] !== undefined) return JSON.stringify(node["const"]);
  if (Array.isArray(node["enum"]))
    return node["enum"].map((value) => JSON.stringify(value)).join(" | ");

  switch (node["type"]) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${toType((node["items"] ?? {}) as Record<string, unknown>, indent)}[]`;
    case "object":
      return toObject(node, indent);
    default:
      return "unknown";
  }
}

function toObject(node: Record<string, unknown>, indent: string): string {
  const properties = (node["properties"] ?? {}) as Record<string, Record<string, unknown>>;
  const required = new Set((node["required"] ?? []) as string[]);
  const inner = `${indent}  `;
  const lines: string[] = ["{"];

  for (const [name, property] of Object.entries(properties)) {
    const description = property["description"];
    if (typeof description === "string") lines.push(`${inner}/** ${description} */`);
    const optional = required.has(name) ? "" : "?";
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
    lines.push(`${inner}${key}${optional}: ${toType(property, inner)};`);
  }
  lines.push(`${indent}}`);
  return lines.join("\n");
}

const typeLines: string[] = [
  `// ${BANNER}`,
  "//",
  "// TypeScript types for every Agent Connect event, with no dependency on zod. Import the",
  "// schemas from `@chipschat/protocol` when you need to validate; import these when you only",
  "// need the shape.",
  "",
  `export const PROTOCOL_VERSION = ${PROTOCOL_VERSION};`,
  "",
];

for (const event of EVENTS) {
  const json = jsonSchemas.get(event.type);
  if (json === undefined) continue;
  typeLines.push(`/** \`${event.type}\` — ${event.summary} */`);
  typeLines.push(`export interface ${pascal(event.type)} ${toObject(json, "")}`);
  typeLines.push("");
}

typeLines.push("/** Any event a harness sends to Chips. */");
typeLines.push(
  `export type HarnessToChipsEvent =\n${EVENTS.filter((e) => e.direction === "harness_to_chips")
    .map((e) => `  | ${pascal(e.type)}`)
    .join("\n")};`,
);
typeLines.push("");
typeLines.push("/** Any event Chips sends to a harness. */");
typeLines.push(
  `export type ChipsToHarnessEvent =\n${EVENTS.filter((e) => e.direction === "chips_to_harness")
    .map((e) => `  | ${pascal(e.type)}`)
    .join("\n")};`,
);
typeLines.push("");
typeLines.push("/** Any Agent Connect event. */");
typeLines.push("export type AnyEvent = HarnessToChipsEvent | ChipsToHarnessEvent;");
emit(TYPES, typeLines.join("\n"));

// --------------------------------------------------------------- Docs reference

const DIRECTION_LABEL: Record<string, string> = {
  harness_to_chips: "Harness → Chips",
  chips_to_harness: "Chips → Harness",
  workspace: "Chips → the log",
};

/** Who writes an event, as its reference page says it. */
const SENDER_LABEL: Record<string, string> = {
  harness: "a harness",
  person: "a person",
  either: "a person or a harness",
  chips: "Chips only; refused from a client",
};

/**
 * A type too long for its cell, said by its shape: `object`, `enum`, or an array of either. An
 * array of risk classes was "object" here once, and a third party took it for one.
 */
function shapeOf(node: Record<string, unknown>): string {
  if (node["type"] === "array")
    return `${shapeOf((node["items"] ?? {}) as Record<string, unknown>)}[]`;
  return Array.isArray(node["enum"]) ? "enum" : "object";
}

/** The closed list a field's values come from, its own or its items'. */
function enumOf(node: Record<string, unknown>): unknown[] | undefined {
  const items = (node["items"] ?? {}) as Record<string, unknown>;
  const values = node["enum"] ?? items["enum"];
  return Array.isArray(values) ? values : undefined;
}

/** One row of the field table. Kept separate so the walker below stays simple. */
function fieldRow(path: string, property: Record<string, unknown>, required: boolean): string {
  const type = toType(property, "").replace(/\n\s*/g, " ").replace(/\|/g, "\\|");
  const long = type.length > 90;
  const rendered = long ? shapeOf(property) : `\`${type}\``;
  const said = String(property["description"] ?? "").replace(/\|/g, "\\|");
  // A long type hides its values in the shape, so the list goes in words beside it.
  const values = long ? enumOf(property) : undefined;
  const description =
    values === undefined
      ? said
      : `${said}${said === "" ? "" : " "}One of ${values.map((value) => `\`${String(value)}\``).join(", ")}.`;
  return `| \`${path}\` | ${required ? "yes" : "no"} | ${rendered} | ${description} |`;
}

/**
 * Every field, flattened to a table row, so the page reads without expanding anything: an
 * object's fields under its name, and an array of objects' under its name and `[]`.
 */
function fieldRows(node: Record<string, unknown>, prefix = ""): string[] {
  const properties = (node["properties"] ?? {}) as Record<string, Record<string, unknown>>;
  const required = new Set((node["required"] ?? []) as string[]);
  const rows: string[] = [];

  for (const [name, property] of Object.entries(properties)) {
    const path = prefix === "" ? name : `${prefix}.${name}`;
    rows.push(fieldRow(path, property, required.has(name)));
    const items = (property["items"] ?? {}) as Record<string, unknown>;
    if (property["type"] === "object" && property["properties"] !== undefined) {
      rows.push(...fieldRows(property, path));
    } else if (property["type"] === "array" && items["properties"] !== undefined) {
      rows.push(...fieldRows(items, `${path}[]`));
    }
  }
  return rows;
}

for (const event of EVENTS) {
  const json = jsonSchemas.get(event.type);
  if (json === undefined) continue;
  const fixturePath = join(FIXTURE_DIR, `${event.type}.json`);
  const fixture = existsSync(fixturePath) ? readFileSync(fixturePath, "utf8").trimEnd() : undefined;

  const page = [
    "---",
    `title: ${yaml(event.type)}`,
    `description: ${yaml(event.summary)}`,
    "---",
    "",
    `<!-- ${BANNER} Edit the schema in packages/protocol/src/events. -->`,
    "",
    event.summary,
    "",
    `**Direction:** ${DIRECTION_LABEL[event.direction]}  `,
    `**Sent by:** ${SENDER_LABEL[event.sender]}  `,
    `**Requires a run:** ${event.requiresRun ? "yes" : "no"}  `,
    `**Schema:** [\`${event.type}.json\`](/schema/${event.type}.json)`,
    "",
    "## Fields",
    "",
    "Every event also carries the [envelope](/reference/envelope/).",
    "",
    "| Field | Required | Type | Description |",
    "| --- | --- | --- | --- |",
    ...fieldRows(json),
    "",
    ...(fixture === undefined ? [] : ["## Example", "", "```json", fixture, "```", ""]),
  ].join("\n");

  emit(join(REFERENCE_DIR, `${slug(event.type)}.md`), page);
}

